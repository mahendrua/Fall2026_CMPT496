def test_rule_paths_win_over_conflicting_project_files(tmp_path):
    write_source(tmp_path / "math_lab.py", "def double(value):\n    return value * 2\n")
    write_source(tmp_path / "Program.cs", "class Program {}\n")
    assert detect_test_language([["math_lab.py"]], codebase_path=str(tmp_path)) == "python"
    assert detect_test_language([["Program.cs"]], codebase_path=str(tmp_path)) == "csharp"


def test_ignored_venv_and_generated_paths_do_not_influence_detection(tmp_path):
    write_source(tmp_path / "Program.cs", "class Program {}\n")
    write_source(tmp_path / ".venv" / "lib" / "site.py", "def ignored():\n    return 1\n")
    write_source(tmp_path / "venv" / "lib.py", "def ignored():\n    return 1\n")
    generated = tmp_path / "checkpoint_tests"
    write_source(generated / GENERATED_MARKER, "Generated by Checkpoint.\n")
    write_source(generated / "test_generated.py", "def test_generated():\n    assert True\n")
    assert detect_test_language([[]], codebase_path=str(tmp_path)) == "csharp"


def test_symlinked_external_source_tree_is_not_counted(tmp_path):
    lab = tmp_path / "lab"
    outside = tmp_path / "outside"
    lab.mkdir()
    write_source(lab / "math_lab.py", "def double(value):\n    return value * 2\n")
    write_source(outside / "Program.cs", "class Program {}\n")
    try:
        (lab / "vendor").symlink_to(outside, target_is_directory=True)
        (lab / "external.cs").symlink_to(outside / "Program.cs")
    except OSError:
        pytest.skip("symlinks are not available on this platform")
    assert detect_test_language([[]], codebase_path=str(lab)) == "python"


def test_scan_budget_exhaustion_fails_closed(tmp_path, monkeypatch):
    write_source(tmp_path / "a.py", "x = 1\n")
    write_source(tmp_path / "b.py", "x = 2\n")
    write_source(tmp_path / "c.py", "x = 3\n")
    monkeypatch.setattr("agent.testing_language.PROJECT_LANGUAGE_SCAN_LIMIT", 2)
    with pytest.raises(ValueError, match="file budget"):
        detect_test_language([[]], codebase_path=str(tmp_path))


def test_ut_agent_run_source_selects_language_before_chroma():
    source = (
        Path(__file__).resolve().parents[2] / "agent" / "UT_agent.py"
    ).read_text(encoding="utf-8")
    run_fn = source.split("def run(self, validated_rules", 1)[1].split("def retriever_node", 1)[0]
    detect_at = run_fn.find("detect_test_language(")
    chroma_at = run_fn.find("PersistentClient(")
    embedding_at = run_fn.find("SentenceTransformerEmbeddingFunction")
    assert detect_at != -1
    assert chroma_at != -1
    assert detect_at < chroma_at
    assert detect_at < embedding_at
    assert "codebase_path=codebase_path" in run_fn


