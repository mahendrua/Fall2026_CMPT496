def make_fixer(llm, context_for=None):
    """
    Build the async function that repairs one broken Vitest test.

    The AI receives the generated test, its Vitest error, and optional
    codebase context. It returns replacement imports and a corrected
    test body using the shared TestRepair schema.
    """

    structured_llm = llm.with_structured_output(TestRepair)

    async def fix(case):
        context = context_for(case) if context_for else ""

        numbered = "\n".join(
            f"{number:4d}  {line}"
            for number, line in enumerate(
                (
                    "\n".join(case.imports)
                    + "\n\n"
                    + case.body
                ).split("\n"),
                1,
            )
        )

        system_message = (
            "You are a senior JavaScript and TypeScript engineer repairing "
            "a generated Vitest test that cannot be loaded or collected. "
            "Fix the underlying test-code problem without changing the "
            "intended behavior being tested."
        )

        prompt = f"""
#### GENERATED TEST ({case.name}.test.js, with line numbers)
{numbered}

#### VITEST ERRORS
{chr(10).join(case.errors)}

#### SOURCE CODE AND ADDITIONAL CODEBASE CONTEXT
{context or "NO ADDITIONAL CONTEXT PROVIDED"}

#### TASK
Return a corrected version of the generated Vitest test.

#### RULES
- `test_method` must contain the complete test body, including describe(),
  it(), or test() declarations. Do not include import statements.
- `imports` must contain every required import statement, one per entry.
- Import Vitest APIs from 'vitest'.
- Preserve the original test's purpose, structure, and assertions.
- Do not weaken, remove, or change assertions simply to make the test pass.
- Use actual exported modules, functions, classes, and members from the
  provided source code. Do not invent APIs or helper functions.
- Preserve JavaScript or TypeScript syntax appropriate to the source test.
- Use valid ES module import syntax.
- Do not introduce Jest, Mocha, or other testing frameworks.
- Do not add package dependencies.
- Do not include Markdown fences or explanatory text.
- If the problem cannot be corrected using the available source and context,
  return an empty `test_method`.
"""

        messages = [
            ("system", system_message),
            ("user", prompt),
        ]

        try:
            output = await structured_llm.ainvoke(messages)

        except (DailyLimitError, RateLimitTimeoutError):
            raise

        except Exception as error:
            progress(
                f"AI repair call failed for {case.name}: {error}"
            )
            return None

        if output is None or not (output.test_method or "").strip():
            return None

        return output.imports or [], output.test_method

    return fix

def _repair(fix, cases, loop):
    """
    Run repair calls using the event loop already used by the agent's LLM.

    This avoids creating a separate event loop for an async LLM client
    that may already be bound to the agent's existing loop.
    """

    async def run_batch():
        semaphore = asyncio.Semaphore(MAX_CONCURRENCY)

        async def guarded(case):
            async with semaphore:
                return await fix(case)

        return await asyncio.gather(
            *(guarded(case) for case in cases)
        )

    if loop is not None:
        return loop.run_until_complete(run_batch())

    temporary = asyncio.new_event_loop()

    try:
        return temporary.run_until_complete(run_batch())
    finally:
        temporary.close()


def check_tests(
    kind,
    prefix,
    cases,
    rejected,
    codebase_path,
    codebase_name,
    results_dir,
    fix=None,
    loop=None,
    max_rounds=MAX_REPAIR_ROUNDS,
):
    """
    Execute and validate generated JavaScript tests using Vitest.

    Tests that fail before collection can be repaired using the supplied
    asynchronous LLM callback. Assertion failures are never repaired.
    """

    run = TestRun(
        kind=kind,
        generated=len(cases) + len(rejected),
        kept=list(cases),
        dropped=list(rejected),
    )

    if not cases:
        return run

    root = Path(codebase_path).resolve()

    if not root.is_dir():
        run.project_error = (
            f"The target codebase directory does not exist: {root}"
        )
        return run

    output_dir = Path(results_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    report_path = output_dir / f"{prefix.lower()}-vitest-results.json"
    run.report_path = str(report_path)
    report_path.unlink(missing_ok=True)

    try:
        node, vitest = _checkpoint_vitest_paths()

        # Keep generated tests under the codebase root so relative imports
        # continue to resolve as they did before repair was introduced.
        with tempfile.TemporaryDirectory(
            prefix="checkpoint-generated-tests-",
            dir=root,
        ) as temporary_directory:

            test_directory = Path(temporary_directory)

            # Initial execution and subsequent repair attempts use the
            # same execution helper.
            parsed = _execute_vitest(
                node,
                vitest,
                root,
                test_directory,
                run.kept,
                report_path,
            )

            for repair_round in range(max_rounds):
                repairable = _find_repairable_cases(
                    run.kept,
                    parsed["repairable_failures"],
                )

                # Nothing remains that can be repaired. This includes
                # ordinary assertion failures.
                if not repairable or fix is None:
                    break

                repair_candidates = []

                for case, error in repairable:
                    case.errors.append(error)

                    if case.repairs >= max_rounds:
                        continue

                    repair_candidates.append(case)

                if not repair_candidates:
                    break

                progress(
                    f"Repairing {len(repair_candidates)} JavaScript "
                    f"test(s), round {repair_round + 1}/{max_rounds}."
                )

                repairs = _repair(
                    fix,
                    repair_candidates,
                    loop,
                )

                repaired_any = False

                for case, repair in zip(repair_candidates, repairs):
                    if not repair:
                        case.reason = (
                            "Vitest could not collect the test, and "
                            "the AI could not repair it"
                        )
                        continue

                    repaired_imports, repaired_body = repair

                    body, imports, reason = clean_test(
                        repaired_body,
                        repaired_imports,
                    )

                    if reason:
                        case.errors.append(
                            f"Repair validation failed: {reason}"
                        )
                        case.reason = (
                            "the AI-generated repair failed validation: "
                            f"{reason}"
                        )
                        continue

                    case.imports = imports
                    case.body = body
                    case.repairs += 1
                    case.reason = ""
                    repaired_any = True

                    progress(
                        f"Repaired JavaScript test {case.name} "
                        f"(attempt {case.repairs}/{max_rounds})."
                    )

                # Drop tests that could not be repaired or whose repaired
                # output failed the harness's validation.
                for case in repair_candidates:
                    if case.reason and case in run.kept:
                        run.kept.remove(case)
                        run.dropped.append(case)

                if not repaired_any or not run.kept:
                    break

                # Re-run all remaining tests. This also verifies that
                # repaired tests now load and collect successfully.
                parsed = _execute_vitest(
                    node,
                    vitest,
                    root,
                    test_directory,
                    run.kept,
                    report_path,
                )

            # Handle tests that remain uncollectable after the final
            # permitted repair round.
            remaining_failures = _find_repairable_cases(
                run.kept,
                parsed["repairable_failures"],
            )

            for case, error in remaining_failures:
                if error not in case.errors:
                    case.errors.append(error)

                case.reason = (
                    f"Vitest could not collect the test after "
                    f"{case.repairs} repair attempt(s)"
                )

                run.kept.remove(case)
                run.dropped.append(case)

            # Store the final report's results. Assertion failures are
            # deliberately retained and reported, not rewritten.
            run.passed = parsed["passed"]
            run.failed = parsed["failed"]
            run.skipped = parsed["skipped"]
            run.failed_tests = parsed["failed_tests"]

    except (RuntimeError, OSError) as error:
        run.project_error = str(error)

    return run


def _execute_vitest(node, vitest, root, test_directory, cases, report_path):
    """Execute the supplied generated tests and parse their Vitest report."""

    report_path.unlink(missing_ok=True)

    test_paths = [
        _write_test_file(test_directory, case)
        for case in cases
    ]

    command = [
        node,
        str(vitest),
        "run",
        "--root",
        str(root),
        "--reporter=json",
        f"--outputFile={report_path}",
        *[str(path) for path in test_paths],
    ]

    try:
        result = subprocess.run(
            command,
            cwd=root,
            capture_output=True,
            text=True,
            timeout=TEST_TIMEOUT_SECONDS,
            check=False,
        )

    except subprocess.TimeoutExpired:
        raise RuntimeError(
            f"Vitest exceeded the {TEST_TIMEOUT_SECONDS}-second "
            "execution timeout."
        )

    except OSError as error:
        raise RuntimeError(
            f"Could not start the Vitest process: {error}"
        ) from error

    try:
        parsed = _parse_vitest_report(report_path)

    except RuntimeError as error:
        output = "\n".join(
            part.strip()
            for part in (result.stdout, result.stderr)
            if part and part.strip()
        )

        message = str(error)

        if output:
            message += f"\n{output[-8000:]}"
        elif result.returncode:
            message += (
                f"\nVitest exited with code {result.returncode}."
            )

        raise RuntimeError(message) from error

    return parsed