MAX_TEST_CHARS = 20_000
TEST_TIMEOUT_SECONDS = 300
MAX_REPAIR_ROUNDS = 2
MAX_REPEATS = 20
MAX_CONCURRENCY = 10

# Vitest test declarations and assertions.
VITEST_IMPORT = re.compile(
    r"""from\s*['"]vitest['"]"""
)

VITEST_TEST = re.compile(
    r"\b(?:describe|it|test)\s*\("
)

VITEST_ASSERTION = re.compile(
    r"\bexpect\s*\("
)

# JavaScript/TypeScript import and export declarations.
IMPORT_LINE = re.compile(
    r"""^\s*(?:import\s+.+?\s+from\s+)?['"][^'"]+['"];?\s*$"""
)


@dataclass
class TestCase:
    """One generated JavaScript test."""

    __test__ = False

    name: str
    imports: list[str]
    body: str
    source: Any = None
    errors: list[str] = field(default_factory=list)
    repairs: int = 0
    reason: str = ""


@dataclass
class TestRun:
    """Execution results for one group of generated tests."""

    __test__ = False

    kind: str
    generated: int = 0
    kept: list[TestCase] = field(default_factory=list)
    dropped: list[TestCase] = field(default_factory=list)
    unusable: int = 0
    passed: int = 0
    failed: int = 0
    skipped: int = 0
    failed_tests: list[str] = field(default_factory=list)
    removed_stale: list[str] = field(default_factory=list)
    project_error: str = ""
    report_path: str = ""

    @property
    def repaired(self):
        """Return tests that were successfully repaired."""
        return [
            case for case in self.kept
            if case.repairs > 0
        ]

    def summary(self):
        return {
            "generated": self.generated,
            "kept": len(self.kept),
            "repaired": [
                {"name": case.name,"repairs": case.repairs,}
                for case in self.repaired
            ],
            "dropped": [
                {"name": case.name, "reason": case.reason}
                for case in self.dropped
            ],
            "passed": self.passed,
            "failed": self.failed,
            "skipped": self.skipped,
            "failed_tests": self.failed_tests,
            "removed_stale_files": self.removed_stale,
            "project_error": self.project_error,
            "html_report": "",
            "json_report": self.report_path,
            "harness": "vitest",
            "validated_at": datetime.now(timezone.utc).isoformat(),
        }

    def message(self):
        if self.project_error:
            return (
                f"{self.kind} tests could not run because the JavaScript "
                f"test environment failed: {self.project_error}"
            )

        if not self.generated:
            return f"No {self.kind.lower()} tests were generated."

        parts = [
            f"{self.kind} tests: {len(self.kept)} of {self.generated} kept"
        ]

        details = []
        if self.dropped:
            did_not_run = len(self.dropped) - self.unusable
            if did_not_run:
                details.append(f"{did_not_run} failed validation or execution setup")
            if self.unusable:
                details.append(f"{self.unusable} were unusable")

        if details:
            parts[0] += f" ({', '.join(details)})"

        if self.kept:
            parts.append(
                f"{self.passed} passed, {self.failed} failed, "
                f"{self.skipped} skipped"
            )
            
        if self.repaired:
            parts.append(
                f"{len(self.repaired)} repaired"
            )

        return ". ".join(parts) + "."
       

    def needs_attention(self):
        return bool(
            self.project_error
            or self.dropped
            or self.failed
            or not self.kept
        )


def _strip_fences(body: str) -> str:
    """Remove Markdown fences around generated source code."""

    body = body.strip()
    body = re.sub(r"^```[\w#+-]*\s*\n", "", body)
    body = re.sub(r"\n?```\s*$", "", body)
    return body.strip()


def _unescape_newlines(body: str) -> str:
    """Convert escaped newlines when the entire answer arrived on one line."""

    if body.count("\n") >= 3 or body.count("\\n") < 3:
        return body

    try:
        return json.loads(f'"{body}"')
    except ValueError:
        return (
            body.replace("\\r\\n", "\n")
            .replace("\\n", "\n")
            .replace("\\t", "\t")
            .replace('\\"', '"')
        )


def normalize_imports(imports):
    """
    Normalize and deduplicate generated JavaScript import statements.

    Unlike C# using directives, JavaScript imports must retain their original
    syntax, including named imports, aliases, and default imports.
    """

    cleaned = []
    seen = set()

    for raw in imports or []:
        line = str(raw).strip()

        if not line:
            continue

        if line.startswith("```") or line.startswith("//"):
            continue

        if not line.startswith(("import ", "export ")):
            continue

        if line not in seen:
            cleaned.append(line)
            seen.add(line)

    return cleaned


def clean_test(body, imports):
    """
    Validate and normalize one generated Vitest test.

    Returns (body, imports, reason). A non-empty reason means rejection.
    """

    body = (body or "").strip()

    if not body:
        return None, imports, "the AI returned an empty test"

    if len(body) > MAX_TEST_CHARS:
        return None, imports, (
            f"the AI's answer was {len(body):,} characters long; "
            "the generated test exceeded the size limit"
        )

    body = _strip_fences(_unescape_newlines(body))

    if re.search(r"(.{8,80}?)\1{%d,}" % (MAX_REPEATS - 1), body, re.DOTALL):
        return None, imports, "the AI got stuck repeating the same text"

    normalized_imports = normalize_imports(imports)

    # The generator must explicitly import Vitest APIs. This avoids
    # accidentally accepting Jest or Mocha tests as Vitest tests.
    combined = "\n".join(normalized_imports + [body])

    if not VITEST_IMPORT.search(combined):
        return None, normalized_imports, (
            "the test does not import its testing APIs from 'vitest'"
        )

    if not VITEST_TEST.search(body):
        return None, normalized_imports, (
            "no Vitest describe(), it(), or test() declaration was found"
        )

    if not VITEST_ASSERTION.search(body):
        return None, normalized_imports, (
            "no expect() assertion was found"
        )

    return body, normalized_imports, ""


def make_cases(prefix, items, body_of, imports_of):
    """
    Clean generated tests and split them into usable and rejected cases.

    Each generated test receives its own file name, such as UT_12.test.js.
    """

    cases, rejected, used = [], [], set()

    for item_id, item in items:
        name = f"{prefix}_{item_id}"

        while name in used:
            name += "_b"

        used.add(name)

        original = body_of(item) or ""
        body, imports, reason = clean_test(
            original,
            imports_of(item),
        )

        case = TestCase(
            name=name,
            imports=imports,
            body=body if body is not None else original,
            source=item,
            reason=reason,
        )

        if reason:
            rejected.append(case)
        else:
            cases.append(case)

    return cases, rejected


def _checkpoint_vitest_paths():
    """Resolve Node.js and the Vitest installation bundled with Checkpoint."""

    checkpoint_root = Path(__file__).resolve().parents[1]
    node = shutil.which("node")
    vitest = checkpoint_root / "node_modules" / "vitest" / "vitest.mjs"

    if not node:
        raise RuntimeError("Node.js was not found on PATH.")

    if not vitest.is_file():
        raise RuntimeError(
            f"Checkpoint's Vitest installation was not found: {vitest}"
        )

    return node, vitest


def _safe_test_filename(name: str) -> str:
    """Convert a generated test name into a safe JavaScript filename."""

    safe_name = re.sub(r"[^A-Za-z0-9_-]", "_", name)
    return f"{safe_name}.test.js"


def _write_test_file(directory: Path, case: TestCase) -> Path:
    """Write one generated test and its imports to an isolated file."""

    test_path = directory / _safe_test_filename(case.name)

    contents = "\n".join(case.imports)
    if contents:
        contents += "\n\n"

    contents += case.body.strip() + "\n"
    test_path.write_text(contents, encoding="utf-8")

    return test_path

def _case_name_from_report_path(file_name: str) -> str:
    """Convert a Vitest report filename back to its generated case name."""

    filename = Path(file_name).name

    if filename.endswith(".test.js"):
        filename = filename[:-len(".test.js")]

    return filename

def _find_repairable_cases(cases, repairable_failures):
    """Match Vitest file-level failures to their generated test cases."""

    cases_by_filename = {
        _safe_test_filename(case.name): case
        for case in cases
    }

    failures = []

    for failure in repairable_failures:
        filename = Path(failure["file_name"]).name
        case = cases_by_filename.get(filename)

        if case is not None:
            failures.append((case, failure["error"]))

    return failures

def _parse_vitest_report(report_path: Path) -> dict:
    """Read and normalize the JSON report produced by Vitest."""

    if not report_path.is_file():
        raise RuntimeError("Vitest did not produce its expected JSON report.")

    try:
        report = json.loads(report_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise RuntimeError(
            f"Could not read the Vitest JSON report: {error}"
        ) from error

    if not isinstance(report, dict):
        raise RuntimeError("Vitest returned an invalid JSON report.")

    test_results = report.get("testResults") or []

    passed = report.get("numPassedTests")
    failed = report.get("numFailedTests")
    skipped = report.get("numPendingTests")

    if passed is None or failed is None or skipped is None:
        statuses = [
            assertion.get("status")
            for test_file in test_results
            for assertion in test_file.get("assertionResults", [])
        ]

        passed = sum(status == "passed" for status in statuses)
        failed = sum(status == "failed" for status in statuses)
        skipped = sum(
            status in {"pending", "skipped", "todo"}
            for status in statuses
        )

    failed_tests = []
    repairable_failures = []

    for test_file in test_results:
        file_name = test_file.get("name", "Unknown test file")
        assertions = test_file.get("assertionResults") or []
        file_status = test_file.get("status")

        # A failed file with no collected assertions indicates that
        # Vitest could not load, transform, or collect the test module.
        # These are candidates for LLM repair.
        if file_status == "failed" and not assertions:
            message = test_file.get("message") or "Unknown Vitest file error"

            failed_tests.append(f"{file_name}: {message}")

            repairable_failures.append({
                "file_name": file_name,
                "error": str(message),
            })

        for assertion in assertions:
            if assertion.get("status") != "failed":
                continue

            test_name = (
                assertion.get("fullName")
                or assertion.get("title")
                or "Unnamed test"
            )
            messages = assertion.get("failureMessages") or []
            detail = "\n".join(str(message) for message in messages)

            failed_tests.append(
                f"{file_name} - {test_name}"
                + (f": {detail}" if detail else "")
            )

    return {
        "passed": int(passed or 0),
        "failed": int(failed or 0),
        "skipped": int(skipped or 0),
        "failed_tests": failed_tests,
        "repairable_failures": repairable_failures,
        "raw": report,
    }


def write_results(run: TestRun, output_dir, to_json):
    """
    Persist generated JavaScript tests and their execution results.

    Args:
        run: Completed Vitest test run.
        output_dir: Directory where Checkpoint stores UT results.
        to_json: Callback that converts a TestCase's source model
            and generated test content into a JSON-compatible dictionary.
    """

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    validated_path = output_dir / "validated_tests.json"
    discarded_path = output_dir / "discarded_tests.json"
    report_path = output_dir / "test_report.json"

    def serialize_case(case):
        """Convert a generated test case into a JSON-compatible record."""

        try:
            record = to_json(case)
        except Exception as error:
            record = {
                "id": case.name,
                "unit_test": case.body,
                "imports": case.imports,
                "serialization_error": str(error),
            }

        if not isinstance(record, dict):
            record = {"data": record}

        return record

    validated = [
        serialize_case(case)
        for case in run.kept
    ]

    discarded = []

    for case in run.dropped:
        record = serialize_case(case)
        record["name"] = case.name
        record["reason"] = case.reason
        record["errors"] = list(case.errors)
        discarded.append(record)

    def write_json(path: Path, data):
        """Write JSON using a temporary file to avoid partial output."""

        temporary_path = path.with_suffix(path.suffix + ".tmp")

        temporary_path.write_text(
            json.dumps(data, indent=4, ensure_ascii=False, default=str),
            encoding="utf-8",
        )

        temporary_path.replace(path)

    write_json(validated_path, validated)
    write_json(discarded_path, discarded)
    write_json(report_path, run.summary())

    return {
        "validated_tests": str(validated_path),
        "discarded_tests": str(discarded_path),
        "test_report": str(report_path),
    }



